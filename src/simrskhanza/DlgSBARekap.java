private void prosesCari() {
    this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
    tabModeSBAR.setRowCount(0);

    try {
       ps = koneksi.prepareStatement(
    "SELECT DATE_FORMAT(p.tgl_perawatan,'%d-%m-%Y') AS tgl_perawatan,"+
    "p.jam_rawat,p.no_rawat,"+
    "r.no_rkm_medis,px.nm_pasien,"+

    "IF(r.status_lanjut='Ralan',"+
    " (SELECT nm_poli FROM poliklinik WHERE kd_poli=r.kd_poli),"+
    " (SELECT b.nm_bangsal FROM kamar_inap ki "+
    "  INNER JOIN kamar k ON ki.kd_kamar=k.kd_kamar "+
    "  INNER JOIN bangsal b ON k.kd_bangsal=b.kd_bangsal "+
    "  WHERE ki.no_rawat=p.no_rawat LIMIT 1)"+
    ") AS ruangan,"+

    "p.situation,p.background,p.assesment,p.recommendation,"+

    "pg.nama AS nama_petugas,"+
    "v.status_validasi,"+
    "DATE_FORMAT(v.tgl_validasi,'%d-%m-%Y') AS tgl_validasi,"+   // ✅ ini
    "v.jam_validasi,"+
    "nv.nama AS nama_validator "+

    "FROM pemeriksaan_ranap_sbar p "+
    "INNER JOIN reg_periksa r ON p.no_rawat=r.no_rawat "+
    "INNER JOIN pasien px ON r.no_rkm_medis=px.no_rkm_medis "+

    "LEFT JOIN validasi_pemeriksaan_sbar v "+
    "ON v.no_rawat=p.no_rawat "+
    "AND v.tgl_perawatan=p.tgl_perawatan "+
    "AND v.jam_rawat=p.jam_rawat "+

    "LEFT JOIN pegawai pg ON p.nip=pg.nik "+
    "LEFT JOIN pegawai nv ON v.nik_validator=nv.nik "+

    "WHERE p.tgl_perawatan BETWEEN ? AND ? "+
    "AND (r.no_rkm_medis LIKE ? OR px.nm_pasien LIKE ?) "+
    "ORDER BY p.tgl_perawatan,p.jam_rawat"
);

        ps.setString(1, Valid.SetTgl(Tgl1.getSelectedItem()+""));
        ps.setString(2, Valid.SetTgl(Tgl2.getSelectedItem()+""));

        ps.setString(3, "%"+TCari.getText().trim()+"%");
        ps.setString(4, "%"+TCari.getText().trim()+"%");
        
        rs = ps.executeQuery();

        int no = 1;

         while(rs.next()){
            String sbar =
                "S: "+rs.getString("situation")+"\n"+
                "B: "+rs.getString("background")+"\n"+
                "A: "+rs.getString("assesment")+"\n"+
                "R: "+rs.getString("recommendation");

            String status = rs.getString("status_validasi");
            if(status == null) status = "Belum";

            String statusGabung =
                status+"\n"+
                rs.getString("tgl_validasi")+"  "+rs.getString("jam_validasi")+"\n"+
                "Petugas: "+rs.getString("nama_petugas")+"\n"+
                "Validator: "+rs.getString("nama_validator");

            tabModeSBAR.addRow(new Object[]{
                no++,
                rs.getString("tgl_perawatan"),
                rs.getString("jam_rawat"),
                rs.getString("no_rawat"),
                rs.getString("no_rkm_medis"),
                rs.getString("nm_pasien"),
                rs.getString("ruangan"),
                sbar,
                statusGabung
            });
        }

    } catch(Exception e){
        System.out.println("Error prosesCari: "+e);
    } finally {
        try {
            if(rs != null) rs.close();
            if(ps != null) ps.close();
        } catch (Exception ex) {
            System.out.println("Error closing: " + ex);
        }
    }

    this.setCursor(Cursor.getDefaultCursor());
}
